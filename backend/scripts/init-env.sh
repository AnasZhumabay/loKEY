#!/usr/bin/env sh
# Creates backend/.env with random local secrets (DB password, server secret key).
# .env is git-ignored: secrets never go into the repository.
#
#   sh scripts/init-env.sh            # once, after cloning
#
# Refuses to overwrite an existing .env (the DB keeps the password it was created with).
set -eu
cd "$(dirname "$0")/.."

if [ -e .env ]; then
  echo ".env already exists — not touching it." >&2
  exit 1
fi

rand() { python3 -c 'import secrets; print(secrets.token_urlsafe(int(__import__("sys").argv[1])))' "$1"; }
DB_PASSWORD=$(rand 24)
SECRET_KEY=$(rand 48)

umask 077   # .env readable only by you
cat > .env <<EOF
# Local secrets, generated by scripts/init-env.sh. NEVER commit this file.
LOKEY_ENV=dev

POSTGRES_USER=lokey
POSTGRES_DB=lokey
POSTGRES_PASSWORD=$DB_PASSWORD

LOKEY_SECRET_KEY=$SECRET_KEY

# Used when running the API / alembic / pytest outside Docker:
LOKEY_DATABASE_URL=postgresql+asyncpg://lokey:$DB_PASSWORD@localhost:5432/lokey
LOKEY_TEST_DATABASE_URL=postgresql+asyncpg://lokey:$DB_PASSWORD@localhost:5432/lokey_test
LOKEY_BLOB_DIR=./data/blobs
EOF
echo "Created .env with fresh random secrets."
